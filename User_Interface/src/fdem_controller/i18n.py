def validate_translations() -> None:
    expected = set(EN)
    for language, catalog in TRANSLATIONS.items():
        missing = expected - set(catalog)
        extra = set(catalog) - expected
        if missing or extra:
            raise ValueError(f"Invalid {language} translation catalog: missing={missing}, extra={extra}")


class Translator:
    def __init__(self, language: str = "en") -> None:
        validate_translations()
        self.language = language if language in TRANSLATIONS else "en"

    def set_language(self, language: str) -> None:
        self.language = language if language in TRANSLATIONS else "en"

    def __call__(self, key: str, **values: object) -> str:
        text = TRANSLATIONS[self.language].get(key, EN.get(key, key))
        return text.format(**values)

    def device_error(self, code: str) -> str:
        return ERRORS[self.language].get(code, code.replace("_", " "))
